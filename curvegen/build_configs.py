"""
Build the 7 Rev F subarray .cfg files by concatenating component configs.

The three components (core 114, spiral 54, mid 46 antennas) are disjoint, so
a subarray config is simply the union of its components' antenna lines.

Run:  /Applications/CASA.app/Contents/MacOS/python3 curvegen/build_configs.py
"""

import os

from config import COMPONENT_CFGS, SUBARRAYS, REVF_DIR, CFG_DIR

HEADER = "# observatory=NGVLA\n# coordsys=XYZ\n"


def read_antenna_lines(component):
    path = os.path.join(REVF_DIR, COMPONENT_CFGS[component])
    with open(path) as f:
        return [ln for ln in f if ln.strip() and not ln.lstrip().startswith("#")]


def inner_core_lines(n_inner=57):
    """Memo 121's CoreInner: the innermost `n_inner` core antennas by 3D
    distance from the core centroid (assumed membership rule -- verify
    against Viviana's antenna list if it ever matters)."""
    import numpy as np
    lines = read_antenna_lines("core")
    xyz = np.array([[float(v) for v in ln.split()[:3]] for ln in lines])
    r = np.sqrt(((xyz - xyz.mean(axis=0)) ** 2).sum(axis=1))
    return [lines[i] for i in np.argsort(r)[:n_inner]]


def build_all():
    os.makedirs(CFG_DIR, exist_ok=True)
    for name, components in SUBARRAYS.items():
        lines = []
        for comp in components:
            lines += inner_core_lines() if comp == "core-inner" \
                else read_antenna_lines(comp)
        out = os.path.join(CFG_DIR, name.replace("+", "_") + ".cfg")
        with open(out, "w") as f:
            f.write("# Rev F subarray '%s' = %s (generated by build_configs.py)\n"
                    % (name, "+".join(components)))
            f.write(HEADER)
            f.writelines(lines)
        print("%-12s %3d antennas -> %s" % (name, len(lines), out))


if __name__ == "__main__":
    build_all()
