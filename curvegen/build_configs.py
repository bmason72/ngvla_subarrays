"""
Build the offered subarray .cfg files by concatenating component configs.

The components (core, spiral, mid, long) are disjoint, so a subarray config is
simply the union of its components' antenna lines.  Which revision's components
are used, and which subarrays are built, follow the active NGVLA_REV (see
config.py): run under `NGVLA_REV=revD casapy build_configs.py` to build the
Rev D set into curvegen/configs-revD_track/.

Run:  /Applications/CASA.app/Contents/MacOS/python3 curvegen/build_configs.py
"""

import os

from config import COMPONENT_CFGS, SUBARRAYS, COMPONENT_DIR, CFG_DIR, REV

HEADER = "# observatory=NGVLA\n# coordsys=XYZ\n"


def read_antenna_lines(component):
    path = os.path.join(COMPONENT_DIR, COMPONENT_CFGS[component])
    with open(path) as f:
        return [ln for ln in f if ln.strip() and not ln.lstrip().startswith("#")]


def inner_core_lines(n_inner=57):
    """Memo 121's CoreInner: the innermost `n_inner` core antennas by 3D
    distance from the core centroid (membership verified antenna-by-antenna
    against Stroh's delivered coreInner.cfg, 6 Jul 2026)."""
    import numpy as np
    lines = read_antenna_lines("core")
    xyz = np.array([[float(v) for v in ln.split()[:3]] for ln in lines])
    r = np.sqrt(((xyz - xyz.mean(axis=0)) ** 2).sum(axis=1))
    return [lines[i] for i in np.argsort(r)[:n_inner]]


def outer_core_lines(n_inner=57):
    """Memo 121's 'outer50core': the core minus its innermost 57 antennas
    (the complement of core-inner)."""
    import numpy as np
    lines = read_antenna_lines("core")
    xyz = np.array([[float(v) for v in ln.split()[:3]] for ln in lines])
    r = np.sqrt(((xyz - xyz.mean(axis=0)) ** 2).sum(axis=1))
    return [lines[i] for i in np.argsort(r)[n_inner:]]


def build_all():
    os.makedirs(CFG_DIR, exist_ok=True)
    for name, components in SUBARRAYS.items():
        lines = []
        for comp in components:
            if comp == "core-inner":
                lines += inner_core_lines()
            elif comp == "core-outer":
                lines += outer_core_lines()
            else:
                lines += read_antenna_lines(comp)
        out = os.path.join(CFG_DIR, name.replace("+", "_") + ".cfg")
        # keep the revF comment byte-identical to the original ("Rev F")
        rev_label = {"revF": "Rev F", "revD": "Rev D"}.get(REV, REV)
        with open(out, "w") as f:
            f.write("# %s subarray '%s' = %s (generated by build_configs.py)\n"
                    % (rev_label, name, "+".join(components)))
            f.write(HEADER)
            f.writelines(lines)
        print("%-12s %3d antennas -> %s" % (name, len(lines), out))


if __name__ == "__main__":
    build_all()
